begin;
create extension if not exists vector with schema extensions;

create table public.companies (
  id uuid primary key default gen_random_uuid(), symbol varchar(32) not null unique,
  name varchar(255) not null, sector varchar(120) not null, exchange varchar(20) not null default 'NSE',
  created_at timestamptz not null default now()
);
create table public.market_prices (
  id bigint generated by default as identity primary key,
  company_id uuid not null references public.companies(id) on delete cascade,
  trading_date date not null, open numeric(18,4) not null check (open >= 0),
  high numeric(18,4) not null check (high >= 0), low numeric(18,4) not null check (low >= 0),
  close numeric(18,4) not null check (close >= 0), volume bigint not null check (volume >= 0),
  source varchar(100) not null, is_cached boolean not null default true,
  retrieved_at timestamptz not null default now(), unique (company_id, trading_date), check (high >= low)
);
create table public.investor_profiles (
  id uuid primary key default gen_random_uuid(), auth_user_id uuid references auth.users(id) on delete cascade,
  name varchar(120) not null, risk_tolerance varchar(10) not null check (risk_tolerance in ('low','medium','high')),
  investment_horizon_years integer not null check (investment_horizon_years > 0),
  max_position_percent numeric(5,2) not null default 10 check (max_position_percent > 0 and max_position_percent <= 100),
  max_sector_percent numeric(5,2) not null default 35 check (max_sector_percent > 0 and max_sector_percent <= 100),
  is_demo boolean not null default false, created_at timestamptz not null default now()
);
create table public.holdings (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.investor_profiles(id) on delete cascade,
  company_id uuid not null references public.companies(id) on delete restrict,
  quantity numeric(18,6) not null check (quantity >= 0), average_cost numeric(18,4) not null check (average_cost >= 0),
  unique (profile_id, company_id)
);
create table public.watchlist_items (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.investor_profiles(id) on delete cascade,
  company_id uuid not null references public.companies(id) on delete cascade,
  created_at timestamptz not null default now(), unique (profile_id, company_id)
);
create table public.financial_documents (
  id uuid primary key default gen_random_uuid(), company_id uuid not null references public.companies(id) on delete cascade,
  title varchar(500) not null, document_type varchar(80) not null, reporting_period varchar(80), source_url text not null,
  source_name varchar(150) not null, published_at date, is_synthetic boolean not null default false,
  checksum varchar(64) unique, created_at timestamptz not null default now()
);
create table public.document_chunks (
  id uuid primary key default gen_random_uuid(),
  document_id uuid not null references public.financial_documents(id) on delete cascade,
  company_id uuid not null references public.companies(id) on delete cascade,
  chunk_index integer not null check (chunk_index >= 0), content text not null check (length(trim(content)) > 0),
  page_number integer check (page_number is null or page_number > 0), section_title varchar(500),
  token_count integer check (token_count is null or token_count > 0), chunk_metadata jsonb not null default '{}'::jsonb,
  embedding extensions.vector(384) not null, unique (document_id, chunk_index)
);
create table public.analysis_sessions (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.investor_profiles(id) on delete restrict,
  company_id uuid not null references public.companies(id) on delete restrict, as_of_date date not null,
  status varchar(12) not null default 'pending' check (status in ('pending','running','completed','degraded','failed')),
  input_snapshot jsonb not null default '{}'::jsonb, metrics jsonb not null default '{}'::jsonb,
  degraded_reasons jsonb not null default '[]'::jsonb, started_at timestamptz not null default now(), completed_at timestamptz
);
create table public.agent_runs (
  id uuid primary key default gen_random_uuid(), session_id uuid not null references public.analysis_sessions(id) on delete cascade,
  agent_name varchar(80) not null,
  status varchar(12) not null default 'pending' check (status in ('pending','running','completed','degraded','failed')),
  input_data jsonb not null default '{}'::jsonb, output_data jsonb, error_code varchar(100), error_message text,
  latency_ms integer check (latency_ms is null or latency_ms >= 0), started_at timestamptz, completed_at timestamptz,
  unique (session_id, agent_name)
);
create table public.recommendations (
  id uuid primary key default gen_random_uuid(), session_id uuid not null unique references public.analysis_sessions(id) on delete cascade,
  classification varchar(80) not null, action varchar(100) not null,
  confidence double precision not null check (confidence between 0 and 1), rationale text not null,
  supporting_evidence jsonb not null default '[]'::jsonb, opposing_evidence jsonb not null default '[]'::jsonb,
  disclaimer text not null, created_at timestamptz not null default now()
);
create table public.citations (
  id uuid primary key default gen_random_uuid(), agent_run_id uuid not null references public.agent_runs(id) on delete cascade,
  document_chunk_id uuid not null references public.document_chunks(id) on delete restrict, claim_key varchar(120) not null,
  quoted_excerpt text, similarity_score double precision check (similarity_score is null or similarity_score between 0 and 1),
  unique (agent_run_id, document_chunk_id, claim_key)
);

create index ix_companies_sector on public.companies(sector);
create index ix_market_prices_company_date on public.market_prices(company_id, trading_date desc);
create index ix_investor_profiles_auth_user on public.investor_profiles(auth_user_id);
create index ix_holdings_profile on public.holdings(profile_id);
create index ix_financial_documents_company on public.financial_documents(company_id);
create index ix_document_chunks_company on public.document_chunks(company_id);
create index ix_document_chunks_embedding_hnsw
  on public.document_chunks using hnsw (embedding extensions.vector_cosine_ops);
create index ix_analysis_sessions_profile on public.analysis_sessions(profile_id);
create index ix_analysis_sessions_company on public.analysis_sessions(company_id);
create index ix_agent_runs_session on public.agent_runs(session_id);
create index ix_citations_agent_run on public.citations(agent_run_id);

create or replace function public.match_document_chunks(
  query_company_id uuid, query_embedding extensions.vector(384),
  match_threshold double precision default 0.55, match_count integer default 5
) returns table (
  chunk_id uuid, document_id uuid, content text, page_number integer,
  section_title varchar, chunk_metadata jsonb, similarity double precision
) language sql stable security invoker set search_path = '' as $$
  select dc.id, dc.document_id, dc.content, dc.page_number, dc.section_title, dc.chunk_metadata,
         1 - (dc.embedding OPERATOR(extensions.<=>) query_embedding) as similarity
  from public.document_chunks dc
  where dc.company_id = query_company_id
    and 1 - (dc.embedding OPERATOR(extensions.<=>) query_embedding) >= match_threshold
  order by dc.embedding OPERATOR(extensions.<=>) query_embedding
  limit least(greatest(match_count, 1), 20)
$$;

alter table public.companies enable row level security;
alter table public.market_prices enable row level security;
alter table public.investor_profiles enable row level security;
alter table public.holdings enable row level security;
alter table public.watchlist_items enable row level security;
alter table public.financial_documents enable row level security;
alter table public.document_chunks enable row level security;
alter table public.analysis_sessions enable row level security;
alter table public.agent_runs enable row level security;
alter table public.recommendations enable row level security;
alter table public.citations enable row level security;

revoke all on function public.match_document_chunks(uuid, extensions.vector, double precision, integer) from public, anon, authenticated;
grant execute on function public.match_document_chunks(uuid, extensions.vector, double precision, integer) to service_role;
grant all on all tables in schema public to service_role;
grant usage, select on all sequences in schema public to service_role;
commit;
